export function botLanguage(value, fallback = 'zh') {
  const source = String(value || '').toLowerCase();
  if (source.startsWith('uk')) return 'uk';
  if (source.startsWith('en')) return 'en';
  if (source.startsWith('zh')) return 'zh';
  return BOT_COPY[fallback] ? fallback : 'zh';
}

export function botText(language, key, values = {}) {
  const copy = BOT_COPY[botLanguage(language)];
  const template = copy[key] ?? BOT_COPY.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}
